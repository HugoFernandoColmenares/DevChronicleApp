import { writeFileSync } from 'node:fs';

import { loadEnv } from './lib/load-env.mjs';

loadEnv();

const firebase = {
  apiKey: process.env.FIREBASE_API_KEY || 'build-placeholder',
  authDomain: process.env.FIREBASE_AUTH_DOMAIN || 'devchronicle-hugo.firebaseapp.com',
  projectId: process.env.FIREBASE_PROJECT_ID || 'devchronicle-hugo',
  storageBucket: process.env.FIREBASE_STORAGE_BUCKET || 'devchronicle-hugo.appspot.com',
  messagingSenderId: process.env.FIREBASE_MESSAGING_SENDER_ID || '000000000000',
  appId: process.env.FIREBASE_APP_ID || '1:000000000000:web:devchronicle',
};

const useEmulators = process.env.FIREBASE_USE_EMULATORS === 'true';
const siteName = process.env.NG_APP_SITE_NAME || 'DevChronicle';
const authorName = process.env.NG_APP_AUTHOR_NAME || 'Hugo Colmenares';

const lines = [
  '// Generated by scripts/write-environment.mjs. Do not commit.',
  'export const environment = {',
  '  production: true,',
  `  siteName: ${JSON.stringify(siteName)},`,
  `  authorName: ${JSON.stringify(authorName)},`,
  `  useEmulators: ${useEmulators},`,
  "  authEmulatorHost: '127.0.0.1',",
  '  authEmulatorPort: 9099,',
  "  firestoreEmulatorHost: '127.0.0.1',",
  '  firestoreEmulatorPort: 8080,',
  '  firebase: {',
  `    apiKey: ${JSON.stringify(firebase.apiKey)},`,
  `    authDomain: ${JSON.stringify(firebase.authDomain)},`,
  `    projectId: ${JSON.stringify(firebase.projectId)},`,
  `    storageBucket: ${JSON.stringify(firebase.storageBucket)},`,
  `    messagingSenderId: ${JSON.stringify(firebase.messagingSenderId)},`,
  `    appId: ${JSON.stringify(firebase.appId)},`,
  '  },',
  '};',
  '',
];

writeFileSync(
  new URL('../src/environments/environment.production.ts', import.meta.url),
  lines.join('\n'),
);
console.log(
  `Wrote environment.production.ts for project ${firebase.projectId} (emulators: ${useEmulators}).`,
);
